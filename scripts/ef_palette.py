#!/usr/bin/env python3
"""Generate a CSS palette from an installed ef-themes theme.

Reads the theme's palette and its semantic mappings (plus the mappings common
to all ef-themes), resolves symbol references to hex colors, and writes CSS
custom properties. Only the standard library is used.

    python3 scripts/ef_palette.py ef-arcadia -o themes/ef-arcadia.css
"""
import argparse
import glob
import os
import re
import sys

# Entries look like `(name "#hex")` or `(name other-name)`; the first entry of a
# quoted list is preceded by `'(`.
HEX = re.compile(r'^\s*(?:\S*\'\()?\(([a-z0-9-]+)\s+"(#[0-9a-fA-F]{6})"\)', re.M)
REF = re.compile(r'^\s*(?:\'\()?\(([a-z0-9-]+)\s+([a-z][a-z0-9-]*)\)+\s*(?:;.*)?$', re.M)

# Semantic names used by templates/base.css -> ef-themes palette/mapping names.
SEMANTIC = {
    'bg': 'bg-main',
    'surface': 'bg-dim',
    'surface-alt': 'bg-alt',
    'popup': 'bg-popup',
    'hl-line': 'bg-hl-line',
    'region': 'bg-region',
    'border': 'border',
    'fg': 'fg-main',
    'fg-dim': 'fg-dim',
    'fg-alt': 'fg-alt',
    'h1': 'fg-heading-1',
    'h2': 'fg-heading-2',
    'h3': 'fg-heading-3',
    'h4': 'fg-heading-4',
    'link': 'fg-link',
    'link-visited': 'fg-link-visited',
    'code': 'fg-prose-code',
    'verbatim': 'fg-prose-verbatim',
    'ok': 'info',
    'warn': 'warning',
    'err': 'err',
    'note': 'identifier',
    'accent': 'accent-2',
    'modeline-bg': 'bg-mode-line-active',
    'modeline-fg': 'fg-mode-line-active',
}


def find_ef_dir(explicit):
    if explicit:
        return explicit
    candidates = sorted(glob.glob(os.path.expanduser('~/.config/emacs/elpa/ef-themes-*'))
                        + glob.glob(os.path.expanduser('~/.emacs.d/elpa/ef-themes-*')))
    if not candidates:
        sys.exit('ef-themes not found; pass --ef-dir')
    return candidates[-1]


def load(ef_dir, theme):
    theme_file = os.path.join(ef_dir, f'{theme}-theme.el')
    common_file = os.path.join(ef_dir, 'ef-themes.el')
    if not os.path.exists(theme_file):
        sys.exit(f'no such theme: {theme_file}')
    theme_src = open(theme_file, encoding='utf-8').read()
    common_src = open(common_file, encoding='utf-8').read() if os.path.exists(common_file) else ''

    colors = dict(HEX.findall(theme_src))
    refs = dict(REF.findall(common_src))
    refs.update(REF.findall(theme_src))  # theme-specific mappings win
    return colors, refs


def resolve(name, colors, refs, depth=0):
    if name in colors:
        return colors[name]
    if depth > 10 or name not in refs:
        return None
    return resolve(refs[name], colors, refs, depth + 1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('theme')
    ap.add_argument('-o', '--output', required=True)
    ap.add_argument('--ef-dir')
    args = ap.parse_args()

    ef_dir = find_ef_dir(args.ef_dir)
    colors, refs = load(ef_dir, args.theme)

    lines = [f'/* Generated by tools/ef_palette.py from {os.path.basename(ef_dir)}/{args.theme}-theme.el.',
             '   Do not edit. Run `make theme` to regenerate. */',
             ':root {']
    for name, value in colors.items():
        lines.append(f'  --ef-{name}: {value};')
    lines.append('')
    missing = []
    for sem, src in SEMANTIC.items():
        value = resolve(src, colors, refs)
        if value is None:
            missing.append(src)
            continue
        lines.append(f'  --{sem}: {value}; /* {src} */')
    lines.append('}')
    if missing:
        sys.exit(f'unresolved palette names: {", ".join(missing)}')

    os.makedirs(os.path.dirname(args.output) or '.', exist_ok=True)
    with open(args.output, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
